from __future__ import annotations

import os
from pathlib import Path


class CredentialManager:
    """Secure secret storage abstraction."""

    def __init__(self, env_prefix: str = "PROMETHEUS") -> None:
        self.env_prefix = env_prefix

    def get_secret(self, name: str) -> str:
        return os.getenv(f"{self.env_prefix}_{name}", "")

    def set_secret(self, name: str, value: str) -> None:
        os.environ[f"{self.env_prefix}_{name}"] = value

    def to_env_file(self, path: str) -> None:
        root = Path(path)
        root.parent.mkdir(parents=True, exist_ok=True)
        with root.open("w", encoding="utf-8") as handle:
            handle.write("# Generated by GENESIS PROMETHEUS\n")
